import json
import pathlib
import random

# Зачем: Фиксирует генератор случайных чисел.
# Теперь при каждом запуске скрипта будут получаться ОДНИ И ТЕ ЖЕ «случайные» данные.
# Это нужно, чтобы результаты тестов анализатора были одинаковыми у всех разработчиков.
random.seed(7)

# Зачем: Это заготовки (справочники) для наполнения полей.
# Из них Python будет случайным образом собирать строки бюджета.
communities = ["Київська ТГ", "Львівська ТГ", "Одеська ТГ", "Харківська ТГ", "Дніпровська ТГ"]
budget_articles = ["Заробітна плата вчителів", "Ремонт доріг та інфраструктури", ...]
budget_types = ["income", "expense"]

# Зачем: Указываем путь к будущему файлу формата JSONL (линейный JSON, где каждая строка — отдельный объект).
path = pathlib.Path("data/large.jsonl")
# Зачем: Автоматически создаем папку "data", если её ещё нет на компьютере, чтобы код не выдал ошибку.
path.parent.mkdir(parents=True, exist_ok=True)

# Зачем: Переменная-память. В ней мы будем хранить копию предыдущей строки, чтобы делать дубликаты.
prev = None

with path.open("w", encoding="utf-8") as f:
    # Зачем: Запускаем цикл, который повторится ровно 200 000 раз. Генерируем большой массив данных.
    for i in range(200_000):
        if i % 10 == 3 and prev is not None:
            row = dict(prev)

        else:
            # Зачем: Создаем стандартную, правильную строку бюджета строго под вашу модель BudgetRow.
            row = {
                # Уникальный код: берем случайный город и добавляем номер (например: "Одеська ТГ-154")
                "code": f"{random.choice(communities)}-{i}",
                # Название статьи: берем из списка + делаем 4000 уникальных вариаций
                "name": f"{random.choice(budget_articles)} {i%4000}",
                # Сумма: если индекс НЕ делится на 7, генерируем случайное число.
                # Если делится на 7 — вставляем текст 'за домовленістю'.
                # Это имитация "грязных" данных, которые анализатор должен будет отловить.
                "amount": str(random.randint(500, 5000)) if i % 7 else "за домовленістю",
                # Направление: случайно выбираем доход это или расход
                "type": random.choice(budget_types),
            }

            # Зачем: Имитация критической ошибки данных. Каждую 1000-ю строку мы намеренно ломаем —
            # зануляем в ней код ('code': ''). Анализатор должен будет отфильтровать такие пустые строки.
            if i % 1000 == 0:
                row = dict(row, code="")

        # Зачем: Запоминаем текущую строку в переменную prev, чтобы на следующем круге цикла её можно было продублировать.
        prev = row

        #  Превращаем Python-словарь в текстовую строку формата JSON и записываем её в файл с новой строки (\n).
        # ensure_ascii=False нужен, чтобы украинские буквы (ї, є, і) записались красиво, а не кодами типа \u0456.
        f.write(json.dumps(row, ensure_ascii=False) + "\n")
