def normalize_name(raw: str | None) -> str:
    """Очищает название бюджетной статьи от лишних пробелов, приводит к нижнему регистру

    и безопасно обрабатывает пустые значения или None.
    """
    # Защита: если названия нет (None) или оно состоит только из пробелов ("   ")
    if not raw or not raw.strip():
        return ""

    # Если текст есть, убираем лишние пробелы между словами и делаем буквы маленькими
    return " ".join(raw.split()).lower()
